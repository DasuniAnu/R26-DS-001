def transcribe_audio_with_whisper(audio_path: Path) -> tuple[str, tuple[str, ...]]:
    """Transcribe an audio file with the configured Whisper runtime."""

    runtime = configured_whisper_runtime()
    if runtime == "xlsr_sinhala":
        transcript = transcribe_audio_with_xlsr_sinhala(audio_path)
    elif runtime == "huggingface":
        transcript = transcribe_audio_with_huggingface_whisper(audio_path)
    elif runtime == "openai_whisper":
        transcript = transcribe_audio_with_openai_whisper(audio_path)
    else:
        transcript = transcribe_audio_with_faster_whisper(audio_path)

    if transcript:
        return transcript, ()
    return "", (f"Whisper runtime '{runtime}' did not produce a transcript.",)


def transcribe_audio_with_huggingface_whisper(audio_path: Path) -> str:
    try:
        import torch
        from transformers import pipeline
    except Exception:
        return ""

    try:
        device = 0 if torch.cuda.is_available() else -1
        model_name = configured_whisper_model("huggingface")
        cache_key = (model_name, device)
        with _MODEL_CACHE_LOCK:
            transcriber = _HUGGINGFACE_WHISPER_CACHE.get(cache_key)
            if transcriber is None:
                transcriber = pipeline(
                    "automatic-speech-recognition",
                    model=model_name,
                    device=device,
                )
                _HUGGINGFACE_WHISPER_CACHE[cache_key] = transcriber
        result = transcriber(str(audio_path), generate_kwargs={"language": "sinhalese", "task": "transcribe"})
        if isinstance(result, dict):
            return clean_text(result.get("text", ""))
        return clean_text(result)
    except Exception:
        return ""


def transcribe_audio_with_xlsr_sinhala(audio_path: Path) -> str:
    """Transcribe Sinhala audio with the janiduchamika XLS-R CTC model."""

    try:
        import numpy as np
        import torch
        from transformers import AutoModelForCTC, AutoProcessor
    except Exception:
        return transcribe_audio_with_xlsr_subprocess(audio_path)

    try:
        audio = decode_audio_array_16k(audio_path, np)
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        model_name = configured_whisper_model("xlsr_sinhala")
        use_fp16 = os.environ.get("XLSR_FP16", "").strip().lower() in {"1", "true", "yes"}
        cache_key = (model_name, str(device), use_fp16)
        if cache_key not in _XLSR_MODEL_CACHE:
            processor = AutoProcessor.from_pretrained(model_name)
            model = AutoModelForCTC.from_pretrained(model_name)
            model.to(device)
            if device.type == "cuda" and use_fp16:
                model.half()
            model.eval()
            _XLSR_MODEL_CACHE[cache_key] = (processor, model)
        processor, model = _XLSR_MODEL_CACHE[cache_key]
        inputs = processor(audio, sampling_rate=16000, return_tensors="pt", padding=True)
        inputs = {key: value.to(device) for key, value in inputs.items()}
        with torch.no_grad():
            logits = model(**inputs).logits
        predicted_ids = torch.argmax(logits, dim=-1)
        return clean_text(processor.batch_decode(predicted_ids)[0])
    except Exception:
        return transcribe_audio_with_xlsr_subprocess(audio_path)


def transcribe_audio_with_xlsr_subprocess(audio_path: Path) -> str:
    python_executable = xlsr_python_executable()
    if not python_executable or not XLSR_TRANSCRIBE_SCRIPT.exists():
        return ""
    command = [
        python_executable,
        str(XLSR_TRANSCRIBE_SCRIPT),
        "--audio-path",
        str(audio_path.resolve()),
        "--model-name",
        configured_whisper_model("xlsr_sinhala"),
        "--local-files-only",
        "--cpu",
    ]
    try:
        result = subprocess.run(
            command,
            check=False,
            capture_output=True,
            text=True,
            encoding="utf-8",
            timeout=max(180, int(audio_duration_seconds(audio_path)) * 4),
        )
    except (OSError, subprocess.SubprocessError, ValueError):
        return ""
    if result.returncode != 0:
        return ""
    lines = [clean_text(line) for line in (result.stdout or "").splitlines() if clean_text(line)]
    return lines[-1] if lines else ""


def xlsr_python_executable() -> str:
    configured = clean_text(os.environ.get("XLSR_PYTHON", ""))
    candidates = [
        configured,
        str(Path.home() / "AppData" / "Local" / "Programs" / "Python" / "Python311" / "python.exe"),
        shutil.which("python") or "",
        sys.executable,
    ]
    for candidate in candidates:
        if candidate and Path(candidate).exists():
            return candidate
    return ""


def decode_audio_array_16k(audio_path: Path, np_module) -> object:
    result = subprocess.run(
        [
            "ffmpeg",
            "-nostdin",
            "-hide_banner",
            "-loglevel",
            "error",
            "-i",
            str(audio_path),
            "-ac",
            "1",
            "-ar",
            "16000",
            "-f",
            "s16le",
            "-",
        ],
        check=True,
        stdout=subprocess.PIPE,
    )
    return np_module.frombuffer(result.stdout, np_module.int16).astype(np_module.float32) / 32768.0


def transcribe_audio_with_faster_whisper(audio_path: Path) -> str:
    try:
        from faster_whisper import WhisperModel  # type: ignore
    except ImportError:
        return ""

    try:
        model_name = configured_whisper_model("faster_whisper")
        device = configured_faster_whisper_device()
        compute_type = configured_faster_whisper_compute_type(device)
        cache_key = (model_name, device, compute_type)
        with _MODEL_CACHE_LOCK:
            model = _FASTER_WHISPER_MODEL_CACHE.get(cache_key)
            if model is None:
                model_options: dict[str, int] = {}
                try:
                    cpu_threads = int(os.environ.get("WHISPER_CPU_THREADS", "0"))
                except ValueError:
                    cpu_threads = 0
                if cpu_threads > 0:
                    model_options["cpu_threads"] = cpu_threads
                model = WhisperModel(
                    model_name,
                    device=device,
                    compute_type=compute_type,
                    **model_options,
                )
                _FASTER_WHISPER_MODEL_CACHE[cache_key] = model
        beam_size = configured_whisper_beam_size()
        segments, _ = model.transcribe(
            str(audio_path),
            language="si",
            vad_filter=True,
            beam_size=beam_size,
            best_of=beam_size,
        )
        return clean_text(" ".join(clean_text(segment.text) for segment in segments))
    except Exception:
        return ""


