def transcript_cache_path(video_id: str) -> Path:
    return AUDIO_CACHE_DIR / f"{video_id}.transcript.txt"


def read_cached_transcript(video_id: str) -> str:
    path = transcript_cache_path(video_id)
    if path.exists():
        return clean_text(path.read_text(encoding="utf-8"))
    return ""


def write_cached_transcript(video_id: str, transcript: str) -> None:
    transcript = clean_text(transcript)
    if not transcript:
        return
    AUDIO_CACHE_DIR.mkdir(parents=True, exist_ok=True)
    transcript_cache_path(video_id).write_text(transcript, encoding="utf-8")


def fetch_youtube_metadata(
    video_id: str,
    api_key: str | None = None,
    use_audio_fallback: bool = True,
    transcript_languages: tuple[str, ...] | None = None,
    allow_transcript_language_fallback: bool = True,
) -> YouTubeMetadata:
    """Fetch title, description, thumbnail, and transcript for a YouTube video."""

    api_key = api_key or os.environ.get("YOUTUBE_API_KEY", "")
    video_id = extract_video_id(video_id)
    if not video_id:
        return YouTubeMetadata(video_id="", warnings=("Missing or invalid YouTube video id.",))

    transcript, transcript_warnings = fetch_youtube_transcript(
        video_id,
        languages=transcript_languages,
        allow_language_fallback=allow_transcript_language_fallback,
    )
    if not transcript and use_audio_fallback:
        audio_transcript, audio_warnings = fetch_audio_transcript(video_id)
        transcript = audio_transcript
        transcript_warnings = audio_warnings if audio_transcript else (*transcript_warnings, *audio_warnings)
    elif not transcript and not use_audio_fallback:
        transcript_warnings = (
            *transcript_warnings,
            "Audio transcript fallback is disabled for YouTube Data API v3 test loading.",
        )

    if not api_key:
        fallback = fetch_youtube_page_metadata(video_id)
        warnings = [
            "YOUTUBE_API_KEY is not set; using public YouTube page metadata where available.",
            *fallback.warnings,
            *transcript_warnings,
        ]
        return YouTubeMetadata(
            video_id=video_id,
            title=fallback.title,
            description=fallback.description,
            thumbnail_url=fallback.thumbnail_url,
            transcript=transcript,
            source="youtube_page",
            warnings=tuple(warnings),
        )

    response = requests.get(
        YOUTUBE_VIDEOS_API,
        params={"part": "snippet", "id": video_id, "key": api_key},
        timeout=15,
    )
    response.raise_for_status()
    payload = response.json()
    items = payload.get("items", [])
    if not items:
        return YouTubeMetadata(video_id=video_id, warnings=("YouTube API returned no video item.",))

    snippet = items[0].get("snippet", {})
    thumbnails = snippet.get("thumbnails", {})
    thumbnail_url = ""
    for quality in ("maxres", "standard", "high", "medium", "default"):
        if thumbnails.get(quality, {}).get("url"):
            thumbnail_url = clean_text(thumbnails[quality]["url"])
            break

    return YouTubeMetadata(
        video_id=video_id,
        title=clean_text(snippet.get("title", "")),
        description=clean_text(snippet.get("description", "")),
        thumbnail_url=thumbnail_url,
        transcript=transcript,
        source="youtube_api",
        warnings=transcript_warnings,
    )


def fetch_youtube_page_metadata(video_id: str) -> YouTubeMetadata:
    """Best-effort title, description, and thumbnail fallback without a Data API key."""

    video_id = extract_video_id(video_id)
    if not video_id:
        return YouTubeMetadata(video_id="", warnings=("Missing or invalid YouTube video id.",))

    title = ""
    description = ""
    thumbnail_url = f"https://i.ytimg.com/vi/{video_id}/hqdefault.jpg"
    warnings: list[str] = []

    try:
        response = requests.get(
            YOUTUBE_OEMBED_API,
            params={"url": f"https://www.youtube.com/watch?v={video_id}", "format": "json"},
            headers=YOUTUBE_HEADERS,
            timeout=10,
        )
        if response.ok:
            payload = response.json()
            title = clean_text(payload.get("title", ""))
            thumbnail_url = clean_text(payload.get("thumbnail_url", "")) or thumbnail_url
    except requests.RequestException:
        warnings.append("Could not fetch public YouTube oEmbed metadata.")

    try:
        response = requests.get(
            YOUTUBE_WATCH_URL,
            params={"v": video_id},
            headers=YOUTUBE_HEADERS,
            timeout=15,
        )
        if response.ok:
            html = response.text
            title = title or extract_meta_content(html, "title")
            description = extract_meta_content(html, "description")
            thumbnail_url = extract_meta_content(html, "image") or thumbnail_url
        else:
            warnings.append("Could not fetch the YouTube watch page metadata.")
    except requests.RequestException:
        warnings.append("Could not fetch the YouTube watch page metadata.")

    return YouTubeMetadata(
        video_id=video_id,
        title=title,
        description=description,
        thumbnail_url=thumbnail_url,
        source="youtube_page",
        warnings=tuple(warnings),
    )


def fetch_youtube_transcript(
    video_id: str,
    languages: tuple[str, ...] | None = None,
    allow_language_fallback: bool = True,
) -> tuple[str, tuple[str, ...]]:
    """Fetch captions/transcript for a YouTube video when captions are publicly available."""

    video_id = extract_video_id(video_id)
    if not video_id:
        return "", ("Missing or invalid YouTube video id.",)

    use_shared_cache = languages is None and allow_language_fallback
    if use_shared_cache:
        cached = read_cached_transcript(video_id)
        if cached:
            return cached, ()

    languages = languages or PREFERRED_TRANSCRIPT_LANGUAGES
    transcript = fetch_transcript_with_package(
        video_id,
        languages=languages,
        allow_language_fallback=allow_language_fallback,
    )
    if transcript:
        if use_shared_cache:
            write_cached_transcript(video_id, transcript)
        return transcript, ()

    try:
        response = requests.get(
            YOUTUBE_WATCH_URL,
            params={"v": video_id},
            headers=YOUTUBE_HEADERS,
            timeout=15,
        )
        response.raise_for_status()
        caption_tracks = parse_caption_tracks(response.text)
        transcript = fetch_transcript_from_caption_tracks(
            caption_tracks,
            languages=languages,
            allow_language_fallback=allow_language_fallback,
        )
        if transcript:
            if use_shared_cache:
                write_cached_transcript(video_id, transcript)
            return transcript, ()
    except (requests.RequestException, ValueError, json.JSONDecodeError):
        pass

    language_text = ", ".join(languages)
    return "", (f"Transcript was not available from public YouTube captions for languages: {language_text}.",)


def fetch_audio_transcript(video_id: str) -> tuple[str, tuple[str, ...]]:
    """Download audio and transcribe it with a local Whisper-compatible model."""

    result = generate_whisper_transcript(video_id, force_refresh=False)
    return result.transcript, result.warnings


def generate_whisper_transcript(video_id: str, force_refresh: bool = False) -> WhisperTranscriptResult:
    """Explicitly download YouTube audio and transcribe it with the configured Whisper runtime."""

    video_id = extract_video_id(video_id)
    runtime = configured_whisper_runtime()
    model_name = configured_whisper_model(runtime)
    if not video_id:
        return WhisperTranscriptResult(
            video_id="",
            warnings=("Missing or invalid YouTube video id.",),
            runtime=runtime,
            model_name=model_name,
        )

    cached = "" if force_refresh else read_cached_transcript(video_id)
    if cached:
        audio_path = cached_youtube_audio(video_id)
        return WhisperTranscriptResult(
            video_id=video_id,
            transcript=cached,
            warnings=("Transcript loaded from local cache.",),
            audio_duration_seconds=audio_duration_seconds(audio_path) if audio_path else 0,
            model_name=model_name,
            runtime=runtime,
            audio_path=str(audio_path) if audio_path else "",
        )

    status = audio_transcript_status()
    if not status["ffmpeg"]:
        return WhisperTranscriptResult(
            video_id=video_id,
            warnings=("Audio transcript generation needs ffmpeg on PATH.",),
            model_name=model_name,
            runtime=runtime,
        )
    if not status["yt_dlp"]:
        return WhisperTranscriptResult(
            video_id=video_id,
            warnings=("Audio transcript generation needs yt-dlp installed.",),
            model_name=model_name,
            runtime=runtime,
        )
    if not status["whisper_backend"]:
        warning = (
            "Audio transcript generation needs faster-whisper, Hugging Face Whisper dependencies, "
            "or a working openai-whisper install. YouTube Data API metadata can still be used without audio transcription."
        )
        if status.get("openai_whisper_error"):
            warning = f"{warning} OpenAI Whisper is currently unavailable: {status['openai_whisper_error']}"
        return WhisperTranscriptResult(video_id=video_id, warnings=(warning,), model_name=model_name, runtime=runtime)

    # All supported ASR runtimes can decode the downloaded m4a/webm stream.
    # Skipping the intermediate WAV removes a full-file conversion and large write.
    audio_path, download_warnings = download_youtube_audio(video_id, convert_to_wav=False)
    if not audio_path:
        return WhisperTranscriptResult(video_id=video_id, warnings=download_warnings, model_name=model_name, runtime=runtime)

    transcript, whisper_warnings = transcribe_audio_with_whisper(audio_path)
    duration = audio_duration_seconds(audio_path)
    if transcript:
        write_cached_transcript(video_id, transcript)
        return WhisperTranscriptResult(
            video_id=video_id,
            transcript=transcript,
            warnings=("Transcript was generated from downloaded audio with Whisper.", *whisper_warnings),
            audio_duration_seconds=duration,
            model_name=model_name,
            runtime=runtime,
            audio_path=str(audio_path),
        )
    return WhisperTranscriptResult(
        video_id=video_id,
        warnings=whisper_warnings,
        audio_duration_seconds=duration,
        model_name=model_name,
        runtime=runtime,
        audio_path=str(audio_path),
    )


def download_youtube_audio(
    video_id: str,
    max_duration_seconds: int | None = MAX_AUDIO_TRANSCRIPT_SECONDS,
    context: str = "Audio transcript fallback",
    convert_to_wav: bool = True,
) -> tuple[Path | None, tuple[str, ...]]:
    """Download audio and optionally convert it to 16 kHz mono WAV."""

    try:
        from yt_dlp import YoutubeDL  # type: ignore
    except ImportError:
        return None, (f"{context} needs yt-dlp installed.",)

    AUDIO_CACHE_DIR.mkdir(parents=True, exist_ok=True)
    url = f"https://www.youtube.com/watch?v={video_id}"
    output_template = str(AUDIO_CACHE_DIR / f"{video_id}.%(ext)s")
    wav_path = AUDIO_CACHE_DIR / f"{video_id}.wav"

    cached_audio = cached_youtube_audio(video_id)
    if cached_audio:
        if cached_audio.suffix.lower() == ".wav" or not convert_to_wav:
            return cached_audio, ()
        warning = convert_audio_to_wav(cached_audio, wav_path, max_duration_seconds=max_duration_seconds, context=context)
        return (None, (warning,)) if warning else (wav_path, ())

    downloaded_info = None
    warnings: list[str] = []
    for options in ytdlp_download_option_sets(output_template):
        try:
            options = dict(options)
            if max_duration_seconds is not None:
                options["match_filter"] = ytdlp_duration_filter(max_duration_seconds, context)
            with YoutubeDL(options) as ydl:
                downloaded_info = ydl.extract_info(url, download=True)
                break
        except Exception as exc:  # noqa: BLE001 - yt-dlp raises broad extractor/download exceptions.
            detail = strip_terminal_codes(str(exc))
            warnings.append(detail)
            if "skipped videos longer than" in detail:
                return None, (detail[detail.find(context) :] if context in detail else detail,)
            continue
    if downloaded_info is None:
        detail = " ".join(warnings[-2:]) if warnings else "unknown yt-dlp error"
        if "403" in detail or "Forbidden" in detail:
            detail = (
                f"{detail} YouTube blocked this download. Try setting YTDLP_COOKIES_BROWSER=chrome "
                "or YTDLP_COOKIES_FILE to an exported cookies.txt, then restart the app."
            )
        return None, (f"{context} could not download audio: {detail}",)

    source_path = downloaded_audio_path(video_id, downloaded_info)
    if not source_path:
        return None, (f"{context} downloaded no usable audio file.",)

    if source_path.suffix.lower() == ".wav" and audio_duration_seconds(source_path) > 0:
        return source_path, ()
    if not convert_to_wav:
        return source_path, ()

    warning = convert_audio_to_wav(source_path, wav_path, max_duration_seconds=max_duration_seconds, context=context)
    if warning:
        return None, (warning,)
    return wav_path, ()


def ytdlp_duration_filter(max_duration_seconds: int, context: str):
    """Reject overlong videos before yt-dlp starts downloading their audio."""

    def reject_overlong_video(info: dict, *, incomplete: bool = False) -> str | None:
        duration = int(info.get("duration") or 0)
        if not incomplete and duration > max_duration_seconds:
            minutes = max_duration_seconds // 60
            return f"{context} skipped videos longer than {minutes} minutes."
        return None

    return reject_overlong_video


def ytdlp_download_option_sets(output_template: str) -> list[dict]:
    """Return yt-dlp option fallbacks for YouTube 403/client blocking cases."""

    base_options = {
        "format": "bestaudio[ext=m4a][protocol^=http]/bestaudio[protocol^=http]/bestaudio/best",
        "noplaylist": True,
        "outtmpl": output_template,
        "quiet": True,
        "no_warnings": True,
        "socket_timeout": 30,
        "retries": 3,
        "fragment_retries": 3,
        "extractor_retries": 3,
        "file_access_retries": 3,
        "overwrites": True,
        "http_headers": YOUTUBE_HEADERS,
        "extractor_args": {"youtube": {"player_client": ["android", "web"]}},
    }
    option_sets = [base_options]
    option_sets.append({**base_options, "extractor_args": {"youtube": {"player_client": ["web_safari", "mweb", "android"]}}})

    cookies_file = clean_text(os.environ.get("YTDLP_COOKIES_FILE", ""))
    if cookies_file:
        option_sets.append({**base_options, "cookiefile": cookies_file})

    cookies_browser = clean_text(os.environ.get("YTDLP_COOKIES_BROWSER", ""))
    if cookies_browser:
        browser_parts = [part.strip() for part in cookies_browser.split(":") if part.strip()]
        option_sets.append({**base_options, "cookiesfrombrowser": tuple(browser_parts)})

    return option_sets


def cached_youtube_audio(video_id: str) -> Path | None:
    wav_path = AUDIO_CACHE_DIR / f"{video_id}.wav"
    if wav_path.exists() and audio_duration_seconds(wav_path) > 0:
        return wav_path
    for path in sorted(AUDIO_CACHE_DIR.glob(f"{video_id}.*"), key=lambda item: item.stat().st_mtime, reverse=True):
        if path.suffix.lower() in {".m4a", ".webm", ".mp3", ".opus"} and audio_duration_seconds(path) > 0:
            return path
    return None


def downloaded_audio_path(video_id: str, info: dict | None = None) -> Path | None:
    """Find the actual audio file yt-dlp produced."""

    candidates: list[Path] = []
    for download in (info or {}).get("requested_downloads", []) or []:
        filepath = clean_text(download.get("filepath") or download.get("filename") or "")
        if filepath:
            candidates.append(Path(filepath))
    filepath = clean_text((info or {}).get("filepath") or (info or {}).get("_filename") or "")
    if filepath:
        candidates.append(Path(filepath))
    candidates.extend(sorted(AUDIO_CACHE_DIR.glob(f"{video_id}.*"), key=lambda path: path.stat().st_mtime, reverse=True))

    ignored_suffixes = {".part", ".ytdl", ".txt"}
    for path in candidates:
        if path.exists() and path.suffix.lower() not in ignored_suffixes and ".transcript" not in path.name:
            return path
    return None


def convert_audio_to_wav(
    source_path: Path,
    wav_path: Path,
    max_duration_seconds: int | None = MAX_AUDIO_TRANSCRIPT_SECONDS,
    context: str = "Audio transcript fallback",
) -> str:
    """Convert downloaded audio to 16 kHz mono WAV for Whisper."""

    if not shutil.which("ffmpeg"):
        return f"{context} needs ffmpeg on PATH."
    try:
        wav_path.parent.mkdir(parents=True, exist_ok=True)
        result = subprocess.run(
            [
                "ffmpeg",
                "-y",
                "-i",
                str(source_path),
                "-vn",
                "-ac",
                "1",
                "-ar",
                "16000",
                "-f",
                "wav",
                str(wav_path),
            ],
            check=False,
            capture_output=True,
            text=True,
            timeout=max_duration_seconds + 120 if max_duration_seconds is not None else None,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        return f"{context} could not convert audio with ffmpeg: {exc}"

    if result.returncode != 0:
        detail = strip_terminal_codes(result.stderr or result.stdout or "Conversion failed.")
        return f"{context} could not convert audio with ffmpeg: {detail[-700:]}"
    if not wav_path.exists() or audio_duration_seconds(wav_path) <= 0:
        return f"{context} converted audio, but the WAV file was not readable."
    return ""


def audio_duration_seconds(audio_path: Path) -> int:
    """Return audio duration when available."""

    if not audio_path.exists():
        return 0
    ffprobe_duration = valid_audio_duration_seconds(audio_path)
    if ffprobe_duration > 0:
        return int(ffprobe_duration)
    try:
        with wave.open(str(audio_path), "rb") as audio:
            frames = audio.getnframes()
            rate = audio.getframerate()
            return int(frames / rate) if rate else 0
    except (wave.Error, OSError):
        return 0


def valid_audio_duration_seconds(audio_path: Path) -> float:
    """Return duration through ffprobe for any ffmpeg-readable audio file."""

    if not shutil.which("ffprobe"):
        return 0.0
    try:
        result = subprocess.run(
            [
                "ffprobe",
                "-v",
                "error",
                "-show_entries",
                "format=duration",
                "-of",
                "default=noprint_wrappers=1:nokey=1",
                str(audio_path),
            ],
            check=False,
            capture_output=True,
            text=True,
            timeout=20,
        )
    except (OSError, subprocess.SubprocessError, ValueError):
        return 0.0
    if result.returncode != 0:
        return 0.0
    try:
        return float((result.stdout or "").strip())
    except ValueError:
        return 0.0


def strip_terminal_codes(value: str) -> str:
    return clean_text(ANSI_ESCAPE_RE.sub("", value))


