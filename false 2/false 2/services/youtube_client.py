def fetch_transcript_with_package(
    video_id: str,
    languages: tuple[str, ...] | None = None,
    allow_language_fallback: bool = True,
) -> str:
    """Use youtube-transcript-api when installed; otherwise return an empty transcript."""

    try:
        from youtube_transcript_api import YouTubeTranscriptApi  # type: ignore
    except ImportError:
        return ""

    languages = languages or PREFERRED_TRANSCRIPT_LANGUAGES
    snippets = None
    try:
        if hasattr(YouTubeTranscriptApi, "get_transcript"):
            snippets = YouTubeTranscriptApi.get_transcript(video_id, languages=list(languages))
        else:
            snippets = YouTubeTranscriptApi().fetch(video_id, languages=list(languages))
    except Exception:
        try:
            transcript_list = YouTubeTranscriptApi.list_transcripts(video_id)
            transcript = None
            for language in languages:
                try:
                    transcript = transcript_list.find_transcript([language])
                    break
                except Exception:
                    continue
            if not transcript and not allow_language_fallback:
                return ""
            transcript = transcript or next(iter(transcript_list), None)
            snippets = transcript.fetch() if transcript else None
        except Exception:
            return ""

    return transcript_from_snippets(snippets or [])


def parse_caption_tracks(html: str) -> list[dict]:
    marker = '"captionTracks":'
    start = html.find(marker)
    if start == -1:
        return []
    decoder = json.JSONDecoder()
    tracks, _ = decoder.raw_decode(html[start + len(marker) :])
    return tracks if isinstance(tracks, list) else []


def fetch_transcript_from_caption_tracks(
    caption_tracks: list[dict],
    languages: tuple[str, ...] | None = None,
    allow_language_fallback: bool = True,
) -> str:
    if not caption_tracks:
        return ""
    track = preferred_caption_track(
        caption_tracks,
        languages=languages,
        allow_language_fallback=allow_language_fallback,
    )
    if not track:
        return ""
    base_url = clean_text(track.get("baseUrl", ""))
    if not base_url:
        return ""
    response = requests.get(with_query_param(unescape(base_url), "fmt", "json3"), timeout=15)
    response.raise_for_status()
    return transcript_from_json3(response.json())


def preferred_caption_track(
    caption_tracks: list[dict],
    languages: tuple[str, ...] | None = None,
    allow_language_fallback: bool = True,
) -> dict:
    languages = languages or PREFERRED_TRANSCRIPT_LANGUAGES
    for language in languages:
        for track in caption_tracks:
            if caption_track_matches_language(track, language):
                return track
    if not allow_language_fallback:
        return {}
    return caption_tracks[0]


def caption_track_matches_language(track: dict, language: str) -> bool:
    """Match exact and regional YouTube caption language variants."""

    wanted = clean_text(language).lower()
    language_code = clean_text(track.get("languageCode", "")).lower()
    if language_code == wanted or language_code.startswith(f"{wanted}-"):
        return True
    if wanted == "si":
        searchable_values = [
            language_code,
            clean_text(track.get("name", {}).get("simpleText", "") if isinstance(track.get("name"), dict) else track.get("name", "")),
            clean_text(track.get("vssId", "")),
            clean_text(track.get("kind", "")),
        ]
        for translation in track.get("translationLanguages", []) or []:
            searchable_values.append(clean_text(translation.get("languageCode", "")))
            name = translation.get("languageName", {})
            searchable_values.append(clean_text(name.get("simpleText", "") if isinstance(name, dict) else name))
        lowered = " ".join(searchable_values).lower()
        return any(marker in lowered for marker in ["sinhala", "sinhalese", "සිංහල", ".si", " si "])
    return False


def with_query_param(url: str, key: str, value: str) -> str:
    parsed = urlparse(url)
    query = parse_qs(parsed.query)
    query[key] = [value]
    return urlunparse(parsed._replace(query=urlencode(query, doseq=True)))


def transcript_from_json3(payload: dict) -> str:
    parts = []
    for event in payload.get("events", []):
        for segment in event.get("segs", []):
            text = clean_text(segment.get("utf8", ""))
            if text:
                parts.append(text)
    return clean_text(" ".join(parts))


def transcript_from_snippets(snippets) -> str:
    parts = []
    for snippet in snippets:
        text = snippet.get("text", "") if isinstance(snippet, dict) else getattr(snippet, "text", "")
        text = clean_text(text)
        if text:
            parts.append(text)
    return clean_text(" ".join(parts))


def extract_meta_content(html: str, property_name: str) -> str:
    patterns = (
        rf'<meta\s+(?:property|name)=["\']og:{re.escape(property_name)}["\']\s+content=["\']([^"\']*)',
        rf'<meta\s+content=["\']([^"\']*)["\']\s+(?:property|name)=["\']og:{re.escape(property_name)}["\']',
        rf'<meta\s+name=["\']{re.escape(property_name)}["\']\s+content=["\']([^"\']*)',
        rf'<meta\s+content=["\']([^"\']*)["\']\s+name=["\']{re.escape(property_name)}["\']',
    )
    for pattern in patterns:
        match = re.search(pattern, html, flags=re.IGNORECASE)
        if match:
            return clean_text(unescape(match.group(1)))
    return ""


def merge_metadata(
    api_metadata: YouTubeMetadata,
    page_data: dict,
    use_transcript: bool = True,
    warn_missing_transcript: bool = True,
) -> YouTubeMetadata:
    """Prefer API title/description and optional browser transcript/page fallbacks."""

    warnings = list(api_metadata.warnings)
    page_title = clean_text(page_data.get("title", ""))
    page_description = clean_text(page_data.get("description", ""))
    page_thumbnail_url = clean_text(page_data.get("thumbnail_url") or page_data.get("thumbnail", ""))
    page_transcript = clean_text(page_data.get("transcript", ""))

    title = api_metadata.title or page_title
    description = api_metadata.description or page_description
    thumbnail_url = api_metadata.thumbnail_url or page_thumbnail_url
    transcript = (api_metadata.transcript or page_transcript) if use_transcript else ""

    if use_transcript and warn_missing_transcript and not transcript:
        warnings.append("Transcript was not found. Open YouTube's transcript panel or paste transcript text for stronger predictions.")
    if not use_transcript:
        warnings.append("Transcript input is disabled for this test; prediction used title and description only.")

    return YouTubeMetadata(
        video_id=api_metadata.video_id or extract_video_id(str(page_data.get("video_id", ""))),
        title=title,
        description=description,
        thumbnail_url=thumbnail_url,
        transcript=transcript,
        source=api_metadata.source,
        warnings=tuple(warnings),
    )
